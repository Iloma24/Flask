    MAIL_PORT = int(os.environ.get('MAIL_PORT') or 25)  # порт сервера. Код int(... or 25) пытается взять порт из настроек,
                                                        # а если его там нет — использует стандартный 25
    MAIL_USE_TLS = os.environ.get('MAIL_USE_TLS') is not None  # флаг безопасности. Если в переменных окружения задано это
                                                        # свойство, будет использоваться шифрование TLS (безопасное соединение).
    MAIL_USERNAME = os.environ.get('MAIL_USERNAME')  # имя пользователя/логин от почты с которого приложение будет
