# это конфигурационный файл, объект класса Config, настраивающий работу фласк-приложения. Для сохранности конфиденциальных
# данных, таких как пароль, я их здесь не прописываю. Они прописаны в .env файле. При запуске скрипта, срабатывает функция
# load_dotenv(), она открывает текстовый файл .env считывает значение запрошенной переменной, и записывает её в оперативную
# память текущего процесса ОС (в окружение). Затем Flask (через модуль os) обращается к операционной системе os.environ.get(),
# ОС мгновенно выдает только что переданное ей значение переменной из load_dotenv(). Схематический процесс выглядит так:
# Файл .env ➔ (читает) ➔ load_dotenv() ➔ (записывает в память) ➔ ОС ➔ (запрашивает) ➔ os.environ.get() ➔ Flask
import os
from dotenv import load_dotenv

basedir = os.path.abspath(os.path.dirname(__file__))  # os.path.dirname - отсекает имя файла, оставляя только путь к папке.
                                # os.path.abspath - превращает путь в абсолютный (полный путь от корня диска, например:
                                # /Users/alex/projects/my_app/). __file__ - это встроенная переменная, которая содержит
                                # путь к текущему файлу (самому config.py). Этот код нужен чтобы программа точно знала,
                                # где находится корень вашего проекта, даже если вы запускаете её из другой папки.
load_dotenv(os.path.join(basedir, '.env'))  # если данные из файла .env будут использоваться при производственном
                                # развертывании приложения, то рекомендуется явно импортировать прописанные в нем переменные
                                # в окружение ОС (os.environ). load_dotenv ищет файл .env и временно загружает его содержимое
                                # в переменные окружения ОС (os.environ) только на время работы приложения.

class Config:
    SECRET_KEY = os.environ.get('SECRET_KEY') or 'you-will-never-guess'  # в данном коде происходит обращение к переменной
                # окружения SECRET_KEY, если в переменной окружения не установлен ключ SECRET_KEY (то есть os.environ.get
                # вернул None), код присваивает элементу переменной окружения SECRET_KEY значение по умолчанию: 'you-will-never-guess'

    SQLALCHEMY_DATABASE_URI = os.environ.get('DATABASE_URL') or 'sqlite:///' + os.path.join(basedir, 'app.db')  # это
                # выражение состоящее из двух вариантов действия. Сначало расширение Flask-SQLAlchemy определяет местоположение
                # базы данных приложения из переменной конфигурации SQLALCHEMY_DATABASE_URI. Так как, в целом хорошей
                # практикой является установка конфигурации из переменных среды и предоставление резервного значения,
                # когда среда не определяет переменную. Конкретно в данном случае я беру URL базы данных из переменной окружения
                # DATABASE_URL, и если это не определено, я настраиваю базу данных с именем app.db, расположенную в главном
                # каталоге приложения, которая хранится в переменной basedir.


