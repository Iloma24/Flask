@appObj.route('/explore')  # страница поиска сообщений
@login_required
def explore():
    """
    Функция выполняет запрос всех сообщений из БД и сохраняет в виде списка упорядоченного по новизне
    :return:
    """
    page = request.args.get('page', 1, type=int)  # page - номер текущей страницы из URL-адреса (например, /index?page=2).
                                        # Если параметра нет, по умолчанию выбирается страница 1. Значение автоматически
                                        # преобразуется в целое число.
    query = sa.select(Post).order_by(Post.timestamp.desc())  # формируется запрос: все посты из таблицы Post, упорядоченные
                                                            # по новизне
    posts = db.paginate(query, page=page, per_page=appObj.config['POSTS_PER_PAGE'], error_out=False)  # разбивает результаты запроса на страницы в соответствии с настроенной пагинацией.
                                        # Пагинация настраивается в конфигурационном файле. Параметр error_out=False защищает
                                        # от ошибок: если затребована несуществующая страница, код просто вернет пустой
                                        # список вместо ошибки 404.
    next_url = url_for('explore', page=posts.next_num) if posts.has_next else None  # получение следующей страницы,
                                        # если она имеется в объекте posts
    prev_url = url_for('explore', page=posts.prev_num) if posts.has_prev else None  # получение предыдующей страницы,
                                        # если она имеется в объекте posts
    return render_template('index.html', title=_('Explore'), posts=posts.items, next_url=next_url,
                           prev_url=prev_url)  # для отображения используется шаблон главной страницы, т.к. вид этих двух
                                        # страниц очень похож, но на странице Explore не будет отображатся форма для
                                        # отправки поста, для такого разграничения использования шаблона, внутри самого
                                        # шаблона прописывается отображение формы с соответствующим условием.  posts.items
                                        # это атрибут, который содержит список элементов, извлеченных для выбранной
                                        # страницы. Также в шаблон передаются значения следующей (next_url) и предыдущей
                                        # (prev_url) страниц


@appObj.route('/reset_password_request', methods=['GET', 'POST'])  # страница СОЗДАНИЯ запроса на сброс пароля, ещё не сброс пароля
def reset_password_request():
    """
    Эта функция просмотра обрабатывает страницу создания запроса сброса пароля. Это ещё не сброс пароля. Сброс пароля
    обрабатывает другая функция просмотра
    :return:
    """
    if current_user.is_authenticated:  # если текущий пользователь авторизован
        return redirect(url_for('index'))  # пользователь перенаправляется на главную страницу
    form = ResetPasswordRequestForm()  # содается форма для запроса сброса пароля
    if form.validate_on_submit():  # метод validate_on_submit() выполняет всю работу по обработке форм. Если выполняется
                                    # GET-запрос, то данный метод пропустит запрос без проверки (там нет форм) и браузер
                                    # вернет страницу с полями для заполнения. Если же выполняется POST-запрос, то метод
                                    # проверит все ли поля заполнены (валидация), если все правильно, выполняется код
                                    # внутри блока if
        user = db.session.scalar(sa.select(User).where(User.email == form.email.data))  # проверяется есть ли в БД имейл
                                    # введенный в форму для запроса сброса пароля
        if user:  # если такой имейл есть
            send_password_reset_email(user)  # функция отправляет пользователю на почту письмо
        flash(_('Check your email for the instructions to reset your password'))  # вывод информационного сообщения в браузер
        return redirect(url_for('login'))  # пользователь перенаправляется на страницу авторизации
    return render_template('reset_password_request.html', title=_('Reset Password'), form=form)  # если
                                    # форма еще не отправлена (или заполнена с ошибками), код отображает HTML-страницу
                                    # reset_password_request.html


@appObj.route('/reset_password/<token>', methods=['GET', 'POST'])  # страница сброса пароля
def reset_password(token):
    """
    Эта функция просмотра проверяет действительность переданного токен и в случае его действительности, позволяет ввести
    в форму ноый пароль
    :param token:
    :return:
    """
    if current_user.is_authenticated:  # если пользователь авторизован, сброс пароля невозможен
        return redirect(url_for('index'))  # пользователь перенаправляется на главную страницу
    user = User.verify_reset_password_token(token)  # проверка токена и получение дпнных пользователя
    if not user:  # если токен не действительный
        return redirect(url_for('index'))  # пользователь перенаправляется на главную страницу
    form = ResetPasswordForm()  # создается форма для ввода нового пароля
    if form.validate_on_submit():  # если форма проходит валидацию
        user.set_password(form.password.data)  # устанавливается новый пароль
        db.session.commit()  # сохранение изменений
        flash(_('Your password has been reset!'))  # информационное сообщение
        return redirect(url_for('login'))  # перенаправление на страницу авторизации
    return render_template('reset_password.html', form=form)  # вызов шаблона ввода нового пароля


