@appObj.before_request  # Декоратор @before_request из Flask регистрирует функцию, которая будет выполняться
                        # непосредственно перед функцией просмотра. Всякая функция после этого декоратора будет выполняться
                        # перед тем, как Flask передаст запрос конкретному обработчику (view-функции).
def before_request():
    """
    Назначение этой функции, выполнять необходимые действия перед HTML-запроса. Конкретно в случае данного приложения, эта
    функция выполняет: проверяет если текущий пользователь авторизован, функция фиксирует текущее время и добавляет это
    время в соответствующую таблицу БД; также эта функция определяет предпочитаемый язык установленный пользователем.
    :return:
    """
    if current_user.is_authenticated:  # проверка авторизации пользователя
        current_user.last_seen = datetime.now(timezone.utc)  # фиксация времени и добавление в БД
        db.session.commit()  # завершение сеанса
    g.local = str(get_locale())  # в g.local записывается строка полученная функцией get_locale (обозначение предпочитаемого
                                # пользователем языка). В дальнейшем это значение может быть динамический использованно
                                # в HTML-шаблоне: <html lang="{{ g.locale }}">


@appObj.route('/', methods=['GET', 'POST'])
@appObj.route('/index', methods=['GET', 'POST'])
@login_required  # защищает ендпоинты от просмотра неавторизованными пользователями. Декоратор перехватывает запрос неавторизованного
                # пользователя и перенаправляет его на страницу авторизации, а после авторизации, перенаправит его обратно.
                # Для этого, декоратор добавит в запрос аргумент next. Для данного ендпоинта запрос будет выглядеть следующим
                # образом: /login?next=/index
def index():
    form = PostForm()  # создается форма для ввода сообщения/записи
    if form.validate_on_submit():  # проверяет, была ли форма отправлена (POST) и валидны ли введенные данные
        try:
            language = detect(form.post.data)  # в функцию detect передается текст поста введенный в форму, для определения языка
        except LangDetectException:  # обработка исключения на случай, если текст пустой или состоит только из цифр/символов
            language = ''  # в этом случае в БД в поле language передается пустая строка
        post = Post(body=form.post.data, author=current_user, language=language)  # создается экземпляр класса "пост".
                                                # Текст берется из формы, автор — это текущий вошедший пользователь (current_user),
                                                # а language это предпочитаемый язык для пользователя
        db.session.add(post)  # добавление поста в БД
        db.session.commit()  # сохранение изменений в БД
        flash(_('Your post is now live!'))  # вывод информационного сообщения
    page = request.args.get('page', 1, type=int)  # page - номер текущей страницы из URL-адреса (например, /index?page=2).
                                        # Если параметра нет, по умолчанию выбирается страница 1. Значение автоматически
                                        # преобразуется в целое число.
    posts = db.paginate(current_user.following_posts(), page=page, per_page=appObj.config['POSTS_PER_PAGE'],
                        error_out=False)  # разбивает результаты запроса на страницы в соответствии с настроенной пагинацией.
                                        # Пагинация настраивается в конфигурационном файле. Параметр error_out=False защищает
                                        # от ошибок: если затребована несуществующая страница, код просто вернет пустой
                                        # список вместо ошибки 404.
    next_url = url_for('index', page=posts.next_num) if posts.has_next else None  # получение следующей страницы,
                                        # если она имеется в объекте posts
    prev_url = url_for('index', page=posts.prev_num) if posts.has_prev else None  # получение предыдующей страницы,
                                        # если она имеется в объекте posts

    return render_template('index.html', title=_('Home'), form=form, posts=posts.items, next_url=next_url,
                           prev_url=prev_url)  # вызов шаблона
                            # для главной страницы. Перезагружает страницу (шаблон Post/Redirect/Get). Это предотвращает
                            # случайную повторную отправку дубликата поста при обновлении страницы пользователем. posts.items
                            # это атрибут, который содержит список элементов, извлеченных для выбранной страницы. Также
                            # в шаблон передаются значения следующей (next_url) и предыдущей (prev_url) страниц


@appObj.route('/translate', methods=['POST'])  # данный маршрут/обработчик работает незаметно для пользователя на «заднем
                            # плане» (в бэкграунде), запрос выполняет JavaScript-код. Этот маршрут принимает текст переданный
                            # пользователем/клиентом на сервер и отправляет его в функцию перевода и возвращает результат
                            # обратно.
@login_required  # декоратор позволяющий доступ к маршруту только авторизованным пользователям
def translate_text():
    """
    Эта функция вызывает функцию translate(), передавая три аргумента непосредственно из данных JSON, которые были
    отправлены вместе с запросом. Результат включается в словарь с помощью единственного ключа с именем text, который
    возвращается в качестве ответа. Flask автоматически переводит словари, возвращаемые функциями просмотра, в формат JSON.
    :return:
    """
    data = request.get_json()  # здесь как раз происходит извлечение текста для перевода, переданного клментом серверу,
                            # а также исходного языка и целевого языка
    return {'text': translate(data['text'],
                              data['source_language'],
                              data['dest_language'])}  # полученные результаты возвращаются в виде словаря. Flask автоматически
                                # превращает возвращаемый словарь {'text': 'переведенный текст'} в формат JSON и отправляет
                                # его обратно в клиенту/браузеру с успешным HTTP-кодом 200 OK


