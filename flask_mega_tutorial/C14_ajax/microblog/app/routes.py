@appObj.route('/register', methods=['GET', 'POST'])
def register():
    """
    Эта функция просмотра. Проверяет что пользователь, вызывающий этот маршрут, не вошел в систему. Форма обрабатывается
    так же, как и форма для входа в систему. Логика, выполняемая внутри условия if validate_on_submit(), создает нового
    пользователя с указанным именем пользователя, электронной почтой и паролем, записывает его в базу данных, а затем
    перенаправляет на приглашение для входа, чтобы пользователь мог войти в систему.
    :return:
    """
    if current_user.is_authenticated:  # если пользователь уже авторизован, он перенаправляется на главную страницу. current_user это атрибут Flask-Login
        return redirect(url_for('index'))
    form = RegistrationForm()  # если не авторизован, предлагается форма для регистрации

    if form.validate_on_submit():  # если данные введенные в форму валидированы
        user = User(username=form.username.data, email=form.email.data)  # создается новый пользователь по введенным в форму данным
        user.set_password(form.password.data)  # хеширование пароля
        db.session.add(user)  # созданный пользователь добавляется в БД
        db.session.commit()  # завершение сессии
        flash(_('Congratulations, you are now a registered user!'))  # отображение сообщения об успешной регистрации
        return redirect(url_for('login'))  # перенаправление на страницу для входа в систему

    return render_template('register.html', title=_('Register'), form=form)  # вызов шаблона для
                            # регистрации пользователя


@appObj.route('/user/<username>')  # маршрут (с динамическим ендпоинтом) страницы профиля пользователя
@login_required  # защищает ендпоинты от просмотра неавторизованными пользователями. Декоратор перехватывает запрос неавторизованного
                # пользователя и перенаправляет его на страницу авторизации, а после авторизации, перенаправит его обратно.
                # Для этого, декоратор добавит в запрос аргумент next. Для данного ендпоинта запрос будет выглядеть следующим
                # образом: /login?next=/<username>
def user(username):
    """
    Данная функция пытается загрузить данные пользователя из БД, используя запрос по его имени. Для
    выполнения запроса используется функция db.first_or_404, эта функция в отличие от db.session.scalar, в случае отсутствия
    результатов отвечающих запросу, возвращает исключение 404, а не None. Если запрос к базе данных не вызывает ошибку 404,
    то это означает, что пользователь с указанным именем пользователя был найден.
    :param username: имя пользователя, получается из динамической части ендпоинта
    :return:
    """
    user = db.first_or_404(sa.select(User).where(User.username == username))  # запрос данных пользователя из БД по имени
                                        # пользователя из URL. Если такого пользователя нет (например, опечатка в URL),
                                        # Flask мгновенно прерывает выполнение и возвращает стандартную ошибку 404 Not Found
    page = request.args.get('page', 1, type=int)  # page - номер текущей страницы из URL-адреса (например, /index?page=2).
                                        # Если параметра нет, по умолчанию выбирается страница 1. Значение автоматически
                                        # преобразуется в целое число.
    query = user.posts.select().order_by(Post.timestamp.desc())  # запрос на отсортированный по новизне всех
                                                                # постов одного пользователя
    posts = db.paginate(query, page=page, per_page=appObj.config['POSTS_PER_PAGE'], error_out=False)  # Разбивает найденные
                                        # посты пользователя на страницы. Количество постов на одну страницу берется из
                                        # глобальных настроек приложения.
    next_url = url_for('user', username=user.username, page=posts.next_num) \
        if posts.has_next else None  # формируется URL для ссылки на следующую страницу
    prev_url = url_for('user', username=user.username, page=posts.prev_num) \
        if posts.has_prev else None  # формируется URL для ссылки на предыдущую страницу
    form = EmptyForm()  # создание формы/кнопки для подписки/отписки пользователя
    return render_template('user.html', user=user, posts=posts.items, next_url=next_url,
                           prev_url=prev_url, form=form)  # применение шаблона user.html и передача в него нужных для
                                                        # прорисовки элементов


@appObj.route('/edit_profile', methods=['GET', 'POST'])  # ендпоинт для редактирования профиля пользователя
@login_required
def edit_profile():
    """
    Эта функция просмотра обрабатывает форму немного по-другому. Она умеет и сохранять новые данные, и показывать старые
    при открытии страницы. Если validate_on_submit() возвращает True, то данные
    внесенные в формы копируются в объект user (для обновления), а затем обновленные данные объекта записываются в БД.
    Но когда validate_on_submit() возвращает False, это может быть вызвано двумя разными причинами. Во-первых, это может
    быть потому, что браузер только что отправил запрос GET, на который мне нужно ответить, предоставив начальную версию
    шаблона формы. Это также может быть, когда браузер отправляет запрос POST с данными формы, но что-то в этих данных
    неверно. Для этой формы мне нужно рассматривать эти два случая отдельно. Когда форма запрашивается в первый раз с
    запросом GET, нужно предварительно заполнить поля данными, которые хранятся в базе данных, поэтому нужно сделать
    обратное тому, что делается в случае отправки, и переместить данные, хранящиеся в полях пользователя, в форму,
    поскольку это гарантирует, что в этих полях формы хранятся текущие данные для пользователя. Но в случае ошибки проверки
    не должно ничего записываться в поля формы, потому что они уже были заполнены WTForms. Чтобы провести различие между
    этими двумя случаями, выполняется проверка request.method, который будет GET для первоначального запроса и POST для
    отправки, которая не прошла проверку
    :return:
    """
    form = EditProfileForm(current_user.username)  # создание формы редактирования профиля. Передается имя текущего пользователя
    if form.validate_on_submit():  # проверяет, соответствуют ли введенные данные установленным валидаторам, нет ли ошибок
                                # (например, не занято ли имя другим юзером)
        current_user.username = form.username.data  # обновляет имя пользователя прямо в объекте текущего пользователя.
                                # Flask-Login и SQLAlchemy «понимают», что это именно та запись, которую нужно изменить
        current_user.about_me = form.about_me.data  # обновление записи "о себе"
        db.session.commit()  # сохранение изменений в БД
        flash(_('Your changes have been saved.'))  # вывод сообщения для пользователя
        return redirect(url_for('edit_profile'))  # !!! ВАЖНО !!! перезагрузка/обновление страницы. Это важно: так пользователь видит
                                # уже обновленные данные, и решается проблема повторной отправки формы при обновлении
                                # страницы браузера.
    elif request.method == 'GET':  # если пользователь только что открыл страницу (еще ничего не нажимал)
        form.username.data = current_user.username  # здесь я беру текущее имя пользователя из базы и вставляю его в
                                # текстовое поле формы. Так пользователю не нужно стирать пустое место и писать имя
                                # заново — он просто правит то, что есть
        form.about_me.data = current_user.about_me  # здесь также происходит правка прежней записи
    return render_template('edit_profile.html', title=_('Edit Profile'), form=form)  # вызов шаблона для
                            # редактирования профиля пользователя


@appObj.route('/follow/<username>', methods=['POST'])  # ендпоинт/маршрут для подписки одного пользователя на другого
@login_required
def follow(username):
    """
    Данная функция реализует логику оформления подписки текущего пользователя на пользователя в ендпоинте
    :param username: имя пользователя на которого подписываются, т.е. из маршруту <username>
    :return:
    """
    form = EmptyForm()  # «пустая форма» со скрытым CSRF-токеном. Это стандартный прием в Flask-WTF для защиты POST-запросов
                        # от подделки. Если токен невалиден, сработает else и пользователя перекинет на главную страницу
    if form.validate_on_submit():  # если форма прошла валидацию, т.е введен правильный CSRF-токен
        user = db.session.scalar(
            sa.select(User).where(User.username == username))  # поиск в БД пользователя с тем именем (username), которое
                                                                # указано в URL
        if user is None:  # если пользователь не найден
            flash(_('User %(username)s not found', username=username))  # выводится соответствующее сообщение
            return redirect(url_for('index'))  # перенаправление на главную страницу
        if user == current_user:  # если пользователь пытается подписаться на себя
            flash(_('You cannot follow yourself!'))  # выводится соответствующее сообщение
            return redirect(url_for('user', username=username))  # перенаправляется на страницу профиля пользователя из маршрута
        current_user.follow(user)  # если не одно из двух условий выше не сработало, то текущий пользователь подписывается
                                    # на найденного пользователя
        db.session.commit()  # сохранение изменений
        flash(_('You are following %(username)s!', username=username))
        return redirect(url_for('user', username=username))  # перенаправляется на страницу профиля пользователя из маршрута
    else:
        return redirect(url_for('index'))  # если форма не прошла валидацию, не верный токен или токен вообще отсутствует,
                                        # то пользователь перенаправляется на главную страницу


